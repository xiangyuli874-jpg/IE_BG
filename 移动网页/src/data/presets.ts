function makeGroups(
  rawGroups: readonly {
    readonly id: string;
    readonly name: string;
    readonly processes: readonly (readonly [number | null, string, string])[];
  }[],
  idPrefix: string
): WorktimeGroup[] {
  return rawGroups.map((group, groupIndex) => ({
    id: `${idPrefix}-${group.id}`,
    name: group.name,
    order: groupIndex + 1,
    processes: group.processes.map((item, processIndex) => ({
      id: `${idPrefix}-${group.id}-${processIndex + 1}`,
      order: processIndex + 1,
      stationNo: item[0],
      sourceKey: item[2],
      name: item[1],
      samples: [...DEFAULT_SAMPLES] as WorktimeProcess["samples"],
      people: 1,
      remark: ""
    }))
  }));
}

